def train_on_batch(X,y, my_model, loss_fn, optimizer):
    batch_loss = 0
    X = torch.from_numpy(X)
    y = torch.from_numpy(y)
    pred = my_model(X.float())
    loss = loss_fn(pred, y)
    batch_loss = loss.item()

    # Backpropagation
    optimizer.zero_grad()
    loss.backward()
    optimizer.step()

    return batch_loss

def count_parameters(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)
